public class apuntesbucles {
    public static void main(String[] args) {
        

        //BUCLE FOR -> cantidad concreta y conocida de repeticiones 
        //Primer hueco : crear la variable i (contador)
        //Segundo hueco : condicion oara que siga contando 
        //Tercer hueco: cunadi incremente la variable en cada repet.

        for (int i = 0; i < 10 ; i++) {
            System.out.println("hola");
        }


    }
}
